def code_para(text):
    for line in text.split("\n"):
        para=doc.add_paragraph()
        r=para.add_run(line); r.font.name="Consolas"; r.font.size=Pt(9.5); r.font.color.rgb=INKCODE

for kind,*rest in B:
    if kind=="h1": doc.add_heading(rest[0],level=1)
    elif kind=="h2": doc.add_heading(rest[0],level=2)
    elif kind=="h3":
        para=doc.add_paragraph(); r=para.add_run(rest[0]); r.bold=True; r.font.size=Pt(11); r.font.color.rgb=BRAND
    elif kind=="p": doc.add_paragraph(rest[0])
    elif kind=="bullets":
        for x in rest[0]: doc.add_paragraph(x,style="List Bullet")
    elif kind=="steps":
        for i,(instr,cmd) in enumerate(rest[0],1):
            # Number explicitly: Word's "List Number" style shares one counter for the
            # whole document, so lab 9 would start at step 89 instead of step 1.
            para=doc.add_paragraph()
            para.paragraph_format.left_indent=Pt(24)
            para.paragraph_format.first_line_indent=Pt(-24)
            r=para.add_run(f"{i}.  "); r.bold=True
            para.add_run(instr)
            if cmd: code_para(cmd)
    elif kind=="code": code_para(rest[0])
    elif kind=="note":
        para=doc.add_paragraph(); r=para.add_run("Note: "); r.bold=True; r.font.color.rgb=BRAND
        para.add_run(rest[0]).font.size=Pt(10)
    elif kind=="rule": doc.add_paragraph("")
    elif kind=="table":
        headers,rows=rest[0],rest[1]
        tb=doc.add_table(rows=0,cols=len(headers)); tb.style="Table Grid"
        hc=tb.add_row().cells
        for i,h in enumerate(headers):
            hc[i].text=""; r=hc[i].paragraphs[0].add_run(h); r.bold=True; r.font.size=Pt(9.5)
            prodoc._shade_cell(hc[i],"E8F0FE")
        for row in rows:
            cc=tb.add_row().cells
            for i,val in enumerate(row):
                cc[i].text=""; cc[i].paragraphs[0].add_run(str(val)).font.size=Pt(9.5)
        doc.add_paragraph("")
    elif kind=="figure":
        path,cap=rest[0],rest[1]
        try:
            doc.add_picture(path,width=Inches(6.2))
            doc.paragraphs[-1].alignment=WD_ALIGN_PARAGRAPH.CENTER
            capp=doc.add_paragraph(); capp.alignment=WD_ALIGN_PARAGRAPH.CENTER
            cr=capp.add_run(cap); cr.italic=True; cr.font.size=Pt(9); cr.font.color.rgb=GREY
        except Exception as e:
            doc.add_paragraph(f"[figure unavailable: {os.path.basename(path)}]")
    elif kind=="dl":
        for term,defn in rest[0]:
            para=doc.add_paragraph(style="List Bullet")
            r=para.add_run(term+" — "); r.bold=True; para.add_run(defn)

prodoc.add_page_numbers(doc)
prodoc.enable_update_fields(doc)
DOCX_OUT=os.path.join(REPO,"courseware",f"LG-{C.SHORT_TITLE}.docx")
doc.save(DOCX_OUT)
print("Saved",DOCX_OUT)
